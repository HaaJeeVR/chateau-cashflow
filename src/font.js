  g('x', [E, E, '#...#', '.#.#.', '..#..', '.#.#.', '#...#']);
  g('y', [E, E, '#...#', '#...#', '#...#', '#...#', '.####', '....#', '.###.']);
  g('z', [E, E, '#####', '...#.', '..#..', '.#...', '#####']);
  // ---- Cijfers
  g('0', ['.###.', '#...#', '#..##', '#.#.#', '##..#', '#...#', '.###.']);
  g('1', ['..#..', '.##..', '..#..', '..#..', '..#..', '..#..', '.###.']);
  g('2', ['.###.', '#...#', '....#', '...#.', '..#..', '.#...', '#####']);
  g('3', ['####.', '....#', '....#', '.###.', '....#', '....#', '####.']);
  g('4', ['...#.', '..##.', '.#.#.', '#..#.', '#####', '...#.', '...#.']);
  g('5', ['#####', '#....', '####.', '....#', '....#', '#...#', '.###.']);
  g('6', ['.###.', '#....', '#....', '####.', '#...#', '#...#', '.###.']);
  g('7', ['#####', '....#', '...#.', '..#..', '.#...', '.#...', '.#...']);
  g('8', ['.###.', '#...#', '#...#', '.###.', '#...#', '#...#', '.###.']);
  g('9', ['.###.', '#...#', '#...#', '.####', '....#', '....#', '.###.']);
  // ---- Leestekens
  g(' ', ['...']);
  g('.', [E, E, E, E, E, E, '#']);
  g(',', [E, E, E, E, E, E, '.#', '#.']);
  g(':', [E, E, '#', E, E, '#']);
  g(';', [E, E, '.#', E, E, '.#', '#.']);
