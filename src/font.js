  g('U', ['#...#', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.']);
  g('V', ['#...#', '#...#', '#...#', '#...#', '#...#', '.#.#.', '..#..']);
  g('W', ['#...#', '#...#', '#...#', '#.#.#', '#.#.#', '#.#.#', '.#.#.']);
  g('X', ['#...#', '#...#', '.#.#.', '..#..', '.#.#.', '#...#', '#...#']);
  g('Y', ['#...#', '#...#', '.#.#.', '..#..', '..#..', '..#..', '..#..']);
  g('Z', ['#####', '....#', '...#.', '..#..', '.#...', '#....', '#####']);
  // ---- Onderkast (x-hoogte rij 2–6)
  g('a', [E, E, '.###.', '....#', '.####', '#...#', '.####']);
  g('b', ['#....', '#....', '####.', '#...#', '#...#', '#...#', '####.']);
  g('c', [E, E, '.###', '#...', '#...', '#...', '.###']);
  g('d', ['....#', '....#', '.####', '#...#', '#...#', '#...#', '.####']);
  g('e', [E, E, '.###.', '#...#', '#####', '#....', '.###.']);
  g('f', ['..##', '.#..', '###.', '.#..', '.#..', '.#..', '.#..']);
  g('g', [E, E, '.####', '#...#', '#...#', '#...#', '.####', '....#', '.###.']);
  g('h', ['#....', '#....', '####.', '#...#', '#...#', '#...#', '#...#']);
  g('i', ['#', '.', '#', '#', '#', '#', '#']);
  g('j', ['..#', '...', '.##', '..#', '..#', '..#', '..#', '..#', '##.']);
  g('k', ['#...', '#...', '#..#', '#.#.', '##..', '#.#.', '#..#']);
  g('l', ['#.', '#.', '#.', '#.', '#.', '#.', '.#']);
  g('m', [E, E, '##.#.', '#.#.#', '#.#.#', '#...#', '#...#']);
  g('n', [E, E, '#.##.', '##..#', '#...#', '#...#', '#...#']);
  g('o', [E, E, '.###.', '#...#', '#...#', '#...#', '.###.']);
  g('p', [E, E, '####.', '#...#', '#...#', '#...#', '####.', '#....', '#....']);
