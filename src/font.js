  const CC = root.CC = root.CC || {};
  const G = {};
  function g(ch, rows) { G[ch] = rows; }
  const E = '';
  // ---- Hoofdletters (rij 0–6)
  g('A', ['.###.', '#...#', '#...#', '#####', '#...#', '#...#', '#...#']);
  g('B', ['####.', '#...#', '#...#', '####.', '#...#', '#...#', '####.']);
  g('C', ['.###.', '#...#', '#....', '#....', '#....', '#...#', '.###.']);
  g('D', ['####.', '#...#', '#...#', '#...#', '#...#', '#...#', '####.']);
  g('E', ['#####', '#....', '#....', '####.', '#....', '#....', '#####']);
  g('F', ['#####', '#....', '#....', '####.', '#....', '#....', '#....']);
  g('G', ['.###.', '#...#', '#....', '#.###', '#...#', '#...#', '.####']);
