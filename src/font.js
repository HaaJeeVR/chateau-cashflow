  // cellTop/cellH: welke rijen de atlas bevat (t.o.v. y van draw). Alles in hele pixels, nooit geschaald (besluit 88).
  function makeFont(Gs, TOPs, cellTop, cellH, lineH, track) {
    const chars = Object.keys(Gs);
    const glyphs = {};
    let atlasW = 0;
    for (const ch of chars) {
      const rows = Gs[ch];
      const w = Math.max(1, ...rows.map(r => r.length));
      glyphs[ch] = { x: atlasW, w, rows, top: TOPs[ch] || 0 };
      atlasW += w + 1;
    }
    const font = {
      lineH,
      glyphs,
      _atlas: null,
      _tints: new Map(),
      _build() {
        const c = document.createElement('canvas');
        c.width = atlasW; c.height = cellH;
        const x = c.getContext('2d');
        x.fillStyle = '#fff';
        for (const ch of chars) {
          const gl = glyphs[ch];
          gl.rows.forEach((r, y) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') x.fillRect(gl.x + i, y + gl.top - cellTop, 1, 1); });
        }
        this._atlas = c;
      },
      tinted(color) {
        if (!this._atlas) this._build();
        let t = this._tints.get(color);
        if (!t) {
          t = document.createElement('canvas');
          t.width = this._atlas.width; t.height = cellH;
          const x = t.getContext('2d');
          x.drawImage(this._atlas, 0, 0);
          x.globalCompositeOperation = 'source-in';
          x.fillStyle = color; x.fillRect(0, 0, t.width, t.height);
          this._tints.set(color, t);
        }
        return t;
      },
      charW(ch) { const gl = glyphs[ch] || glyphs['?']; return gl.w + track; },
      width(str) {
        let w = 0;
        for (const ch of String(str)) w += this.charW(ch);
        return Math.max(0, w - track);
      },
      // Tekst tekenen. opts: {align:'left'|'center'|'right', shadow: kleur}. y = bovenkant van de hoofdletters.
      draw(ctx, str, x, y, color, opts) {
        opts = opts || {};
        str = String(str);
        const w = this.width(str);
        if (opts.align === 'center') x -= Math.floor(w / 2);
        else if (opts.align === 'right') x -= w;
        x = Math.round(x); y = Math.round(y);
        if (opts.shadow) this._run(ctx, str, x + 1, y + 1, opts.shadow);
        this._run(ctx, str, x, y, color);
        return w;
      },
      _run(ctx, str, x, y, color) {
        const img = this.tinted(color);
        let cx = x;
        for (const ch of str) {
          const gl = glyphs[ch] || glyphs['?'];
          ctx.drawImage(img, gl.x, 0, gl.w, cellH, cx, y + cellTop, gl.w, cellH);
          cx += gl.w + track;
        }
      },
      // Afbreken met posities (voor tekstvakken met een cursor): [{s, e}] per regel, \n breekt af,
      // lange woorden (spelcode) worden op letters gebroken. Spaties blijven aan het eind van de regel staan.
      wrapIdx(txt, maxW) {
        txt = String(txt); const out = []; let s = 0; const n = txt.length;
        for (;;) {
          let nl = txt.indexOf('\n', s); if (nl < 0) nl = n;
          if (s === nl) { out.push({ s, e: s }); if (nl === n) break; s = nl + 1; continue; }
          let e = s, w = 0, sp = -1;
          while (e < nl) { const cw = this.charW(txt[e]); if (w + cw - track > maxW && e > s) break; if (txt[e] === ' ') sp = e; w += cw; e++; }
          if (e < nl && sp >= s) e = sp + 1;
          out.push({ s, e });
          s = e;
          if (s === nl) { if (nl === n) break; s = nl + 1; if (s === n) { out.push({ s, e: s }); break; } }
        }
        return out;
      },
      // Woordafbreking op maxW pixels.
      wrap(str, maxW) {
        const words = String(str).split(' ');
        const lines = []; let cur = '';
        for (const w of words) {
          const t = cur ? cur + ' ' + w : w;
          if (this.width(t) > maxW && cur) { lines.push(cur); cur = w; } else cur = t;
        }
        if (cur) lines.push(cur);
        return lines;
      },
    };
    return font;
  }

